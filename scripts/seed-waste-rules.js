const { createClient } = require('@supabase/supabase-js');
const fs = require('fs');
const path = require('path');
require('dotenv').config({ path: '.env.local' });

const wasteRules = require('../src/data/waste_rules.json');

const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL;
// Use SERVICE_ROLE_KEY for seeding (bypasses RLS) or ANON_KEY if RLS allows public write
const supabaseKey = process.env.SUPABASE_SERVICE_ROLE_KEY || process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;

if (!supabaseUrl || !supabaseKey) {
    console.error("Missing Supabase URL or Key in .env.local");
    process.exit(1);
}

const supabase = createClient(supabaseUrl, supabaseKey);

async function seed() {
    console.log("Starting Supabase Seed...");

    // 1. Create table via SQL? Or just insert (assuming table exists)?
    // Supabase client can't create table easily unless using SQL or Migration.
    // Best to assume table exists or create it.
    // For safety, we can try to create table if not exists using SQL function or just instruct user.
    // But let's assume user will create table manually or use migrations.
    // We'll proceed to insert data.

    // Check connection
    const { error: healthCheck } = await supabase.from('waste_rules').select('count', { count: 'exact', head: true });
    if (healthCheck && healthCheck.code === '42P01') { // undefined_table
        console.error("Table 'waste_rules' does not exist. Please create it in Supabase first.");
        console.log(`
SQL to Create Table:
create table waste_rules (
  id bigint generated by default as identity primary key,
  sido text,
  sigungu text,
  "emdNm" text, -- quoted for camelCase
  "gnrlWsteDschrgDay" text,
  "gnrlWsteDschrgMthd" text,
  "foodWsteDschrgDay" text,
  "foodWsteDschrgMthd" text,
  "recycleDschrgDay" text,
  "recycleDschrgMthd" text,
  "dschrgPlace" text,
  "noCollectionDay" text,
  "gnrlWsteDschrgTime" text,
  "foodWsteDschrgTime" text,
  "recycleDschrgTime" text,
  "contact" text
);
`);
        process.exit(1);
    }

    // Batch Insert
    const BATCH_SIZE = 1000;
    for (let i = 0; i < wasteRules.length; i += BATCH_SIZE) {
        const batch = wasteRules.slice(i, i + BATCH_SIZE);

        // Convert keys to match DB? DB column names should match JSON keys if possible.
        // JSON keys are camelCase. Postgres is case-sensitive if quoted, or lower_snake_case if unquoted.
        // We should use quoted identifiers for camelCase columns or rename them.
        // To simplify: we assume table columns are created with quotes "emdNm" etc.
        // OR: Mapping.
        // Let's assume user creates table with matching column names (case sensitive).

        const { error } = await supabase.from('waste_rules').insert(batch);

        if (error) {
            console.error("Insert Error at batch", i, error);
            // decide whether to stop or continue
        } else {
            console.log(`Inserted ${i + batch.length} / ${wasteRules.length}`);
        }
    }

    console.log("Seeding Complete!");
}

seed();
